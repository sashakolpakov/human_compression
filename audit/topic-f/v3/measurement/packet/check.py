 ap=argparse.ArgumentParser();ap.add_argument('--out',type=Path,required=True);ap.add_argument('--render',action='store_true');ap.add_argument('--xelatex',default='xelatex');a=ap.parse_args();C.need(not a.out.exists(),'fresh output directory');a.out.mkdir(parents=True)
 if(H/'manifest.json').exists():
  entries=C.read(H/'manifest.json')['exports'];C.need(len({x['path']for x in entries})==len(entries),'unique exports')
  for row in entries:
   rel=Path(row['path']);C.need(not rel.is_absolute()and '..'not in rel.parts,'relative manifest path');p=H/rel
