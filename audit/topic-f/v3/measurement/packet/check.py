 report=dict(status='PASS_AUTHOR_CHECK_PENDING_DISTINCT_NUMERICAL_REVIEW',coordinates=30,exact_fractions=90,combined_fractions=30,conditional_fractions=60,PDF_component_cells=180,raw_group_cells=90,whole_raw_file_cells=160,cost_csv_rows=270,fraction_csv_rows=90,raw_file_csv_rows=160,semantic_controls=tests['rejected'],figure_checks=figures,graph_checks=graph,graph_controls=graph_controls,reader_pages=3 if a.render else None,source_font_or_science_rerun=False,new_credits=0)
 (a.out/'report.json').write_text(json.dumps(report,indent=2)+'\n');print('PASS30 coordinates/90 fractions; complete programs and applications;11 SVG/PDF bars,7 nodes/9 arrows')
