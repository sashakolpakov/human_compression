from pathlib import Path
from itertools import permutations,product
import json
P=Path(__file__).resolve().parent
def need(x,m):
    if not x:raise ValueError(m)
def save(name,roots,perms,order,details):
    need(all(sorted(x)==list(range(1,len(roots)+1)) for x in perms),'permutation')
    data=dict(name=name,roots=roots,reflection_permutations=perms,expected_order=order,**details)
    (P/(name+'_model.json')).write_text(json.dumps(data,indent=2)+'\n')
    (P/(name+'_model.g')).write_text('modelName:="'+name+'";;\nexpectedOrder:='+str(order)+';;\nmodelPerms:='+str(perms)+';;\nG:=Group(List(modelPerms,PermList));;\n')

# E_n in the integral simple-root basis; all roots are generated by reflections.
for n,number,order in [(6,72,51840),(7,126,2903040),(8,240,696729600)]:
    edges=[(i,i+1)for i in range(n-2)]+[(2,n-1)]
    cartan=[[2 if i==j else -1 if (i,j)in edges or (j,i)in edges else 0 for j in range(n)]for i in range(n)]
    def ref(v,i):
        w=list(v);w[i]-=sum(v[j]*cartan[j][i]for j in range(n));return tuple(w)
    roots={tuple(int(j==i)for j in range(n)) for i in range(n)};todo=list(roots)
    for v in todo:
        for i in range(n):
            w=ref(v,i)
            if w not in roots:roots.add(w);todo.append(w)
        need(len(roots)<=number,'unexpected root growth')
    roots=sorted(roots);need(len(roots)==number,'root count')
    need(all(sum(v[i]*cartan[i][j]*v[j]for i in range(n)for j in range(n))==2 for v in roots),'root norm')
    ix={v:i+1 for i,v in enumerate(roots)}
    save('E'+str(n),roots,[[ix[ref(v,i)]for v in roots]for i in range(n)],order,dict(cartan=cartan))

# H4 in Z[phi], represented by pairs a+b phi, phi^2=phi+1.
def add(x,y):return (x[0]+y[0],x[1]+y[1])
def neg(x):return(-x[0],-x[1])
def mul(x,y):return(x[0]*y[0]+x[1]*y[1],x[0]*y[1]+x[1]*y[0]+x[1]*y[1])
def dot(v,w):
    z=(0,0)
    for a,b in zip(v,w):z=add(z,mul(a,b))
    return z
zero=(0,0);one=(1,0);phi=(0,1);invphi=(-1,1)
roots=set()
for i in range(4):
    for sg in [-1,1]:roots.add(tuple((2*sg,0)if j==i else zero for j in range(4)))
for signs in product([-1,1],repeat=4):roots.add(tuple((sg,0)for sg in signs))
for perm in permutations(range(4)):
    if sum(perm[i]>perm[j]for i in range(4)for j in range(i+1,4))%2:continue
    for signs in product([-1,1],repeat=3):
        base=[zero]+[v if sg==1 else neg(v)for v,sg in zip([one,phi,invphi],signs)]
        roots.add(tuple(base[i]for i in perm))
roots=sorted(roots);need(len(roots)==120 and all(dot(v,v)==(4,0)for v in roots),'H4 roots')
simple=None
for a in roots[:1]:
 for b in roots:
  if dot(a,b)!=(0,-2):continue
  for c in roots:
   if dot(a,c)!=zero or dot(b,c)!=(-2,0):continue
   for d in roots:
    if dot(a,d)==dot(b,d)==zero and dot(c,d)==(-2,0):simple=[a,b,c,d];break
   if simple:break
  if simple:break
need(simple is not None,'H4 simple roots')
def href(v,a):
    z=dot(v,a);need(z[0]%2==z[1]%2==0,'integral reflection coefficient')
    z=(z[0]//2,z[1]//2)
    return tuple(add(x,neg(mul(z,y)))for x,y in zip(v,a))
ix={v:i+1 for i,v in enumerate(roots)}
save('H4',roots,[[ix[href(v,a)]for v in roots]for a in simple],14400,dict(simple_roots=simple,coefficient_convention='a+b phi, phi^2=phi+1; roots scaled by2'))
