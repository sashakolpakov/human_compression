"""Exact path-cocycle witness, independent of GAP or group catalogues.

Run with Python 3. The finite checks cover ranks 2 through 6. The adjoining
written proof establishes the family for every rank; this program does not.
"""
from hashlib import sha256
import json
from pathlib import Path


def check(d):
    vm, em = (1 << d) - 1, (1 << (d - 1)) - 1
    size = 1 << (2 * d - 1)

    def cocycle(v, w):
        return (v >> 1) & w & em

    def mul(a, b):
        return a ^ b ^ (cocycle(a & vm, b & vm) << d)

    def inv(a):
        return a ^ (cocycle(a & vm, a & vm) << d)

    def comm(a, b):
        return mul(mul(mul(inv(a), inv(b)), a), b)

    def closure(gens):
        found, frontier = {0}, [0]
        while frontier:
            a = frontier.pop()
            for b in gens:
                c = mul(a, b)
                if c not in found:
                    found.add(c)
                    frontier.append(c)
        return found

    # The cocycle identity proves associativity on the entire central extension.
    cocycle_checks = 0
    for u in range(1 << d):
        for v in range(1 << d):
            for w in range(1 << d):
                assert cocycle(u, v) ^ cocycle(u ^ v, w) == cocycle(v, w) ^ cocycle(u, v ^ w)
                cocycle_checks += 1
    assert all(mul(a, inv(a)) == mul(inv(a), a) == 0 for a in range(size))
    rho = [1 << i for i in range(d)]
    assert all(mul(r, r) == 0 for r in rho)
    assert len(closure(rho)) == size
    central = [1 << (d + i) for i in range(d - 1)]
    for i in range(d):
        for j in range(i + 1, d):
            assert comm(rho[i], rho[j]) == (central[i] if j == i + 1 else 0)
    assert all(comm(c, r) == 0 for c in central for r in rho)

    parabolics = [closure([rho[i] for i in range(d) if mask >> i & 1])
                  for mask in range(1 << d)]
    for mask, group in enumerate(parabolics):
        internal = mask & (mask >> 1) & em
        formula = {a for a in range(size)
                   if ((a & vm) & ~mask) == 0 and ((a >> d) & ~internal) == 0}
        assert group == formula
    for i, gi in enumerate(parabolics):
        for j, gj in enumerate(parabolics):
            assert gi & gj == parabolics[i & j]

    sigma = [mul(rho[i], rho[i + 1]) for i in range(d - 1)]
    assert [mul(s, s) for s in sigma] == central
    ais, phis = [], []
    for i in range(d - 1):
        gens = sigma.copy()
        gens[i] = mul(gens[i], gens[i])
        ai = closure(gens)
        # For finite 2-groups Phi(H) is generated by all squares in H.
        phi = closure(sorted({mul(a, a) for a in ai}))
        ais.append(ai)
        phis.append(phi)
    intersection = set.intersection(*phis)
    expected = closure(central[1:-1])
    assert intersection == expected
    if d >= 3:
        assert phis[0] == closure(central[1:])
        assert phis[-1] == closure(central[:-1])
        for i in range(1, d - 2):
            assert comm(sigma[i - 1], sigma[i + 1]) == central[i]
            assert phis[i] == closure(central)
    assert len(intersection) == (1 << max(0, d - 3))
    return {
        "rank": d, "order": size, "class": 2,
        "cocycle_identity_checks": cocycle_checks,
        "full_IP_checks": 1 << (2 * d),
        "A_i_orders": list(map(len, ais)),
        "Phi_A_i_orders": list(map(len, phis)),
        "C_order": len(intersection), "source_C_prediction": 1,
        "gamma3_order": 1, "quotient_order": size // len(intersection),
        "counterexample_to_specified_C_claims": d >= 4,
    }


