#!/usr/bin/env python3
"""Replay the coset certificate kernel and concrete proofs with pinned Lean dependencies."""
import argparse,hashlib,json,os,re,shutil,subprocess,sys,time
from pathlib import Path
BASE=Path(__file__).resolve().parent

def need(ok,msg):
 if not ok:raise RuntimeError('P219_REJECT '+msg)
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def main():
 ap=argparse.ArgumentParser(description=__doc__)
 ap.add_argument('--out',type=Path,required=True)
 ap.add_argument('--lean',type=Path,required=True)
 ap.add_argument('--packages',type=Path,required=True)
 a=ap.parse_args();need(not a.out.exists() and not a.out.is_symlink(),'fresh output path')
 out=a.out.resolve();need(not out.exists(),'fresh resolved output path');out.mkdir(parents=True)
 deps=json.loads((BASE/'formal/dependency_manifest.json').read_text());pkgs=a.packages.resolve()
 checked=[]
 for item in deps['packages']:
  p=pkgs/item['name'];rev=subprocess.check_output(['git','-C',str(p),'rev-parse','HEAD'],text=True).strip()
  need(rev==item['rev'],'dependency revision '+item['name'])
  need(subprocess.run(['git','-C',str(p),'diff','--quiet','HEAD','--']).returncode==0,'clean dependency '+item['name'])
  checked.append(dict(name=item['name'],revision=rev))
 version=subprocess.check_output([a.lean,'--version'],text=True).strip();need('version 4.32.2,' in version,'Lean version')
 cache=out/'dependency_cache';cache.mkdir();app=out/'objects';app.mkdir();sources=out/'sources';sources.mkdir()
 origin=pkgs/'mathlib/.lake/build/lib/lean';links=0
 for p in origin.rglob('*'):
  if p.is_file():
   q=cache/p.relative_to(origin);q.parent.mkdir(parents=True,exist_ok=True);q.symlink_to(p);links+=1
 libraries=[str(p/'.lake/build/lib/lean') for p in pkgs.iterdir() if (p/'.lake/build/lib/lean').is_dir()]
 env=dict(os.environ);env['LEAN_PATH']=os.pathsep.join([str(app),str(cache)]+libraries)
 built=[]
 def build(module):
  dest=cache/(module.replace('.','/')+'.olean')
  if dest.exists():return
  src=pkgs/'mathlib'/(module.replace('.','/')+'.lean');need(src.exists(),'missing source '+module)
  dest.parent.mkdir(parents=True,exist_ok=True)
  while True:
   r=subprocess.run([a.lean,'-o',dest,src.relative_to(pkgs/'mathlib')],cwd=pkgs/'mathlib',env=env,text=True,capture_output=True,timeout=120)
   if r.returncode==0:break
   m=re.search(r'of module ([\w.]+) does not exist',r.stdout+r.stderr)
   need(m is not None,r.stdout+r.stderr);build(m[1])
  built.append(dict(module=module,source_sha256=sha(src),object_sha256=sha(dest)))
 build('Mathlib.GroupTheory.PresentedGroup')
 inputs={};runs=[];regenerations=[]
 for producer,subdir,outputs in [
  ('phase219_examples.py','regenerated_examples',[('CosetUpperExamples.lean','phase219_formal/CosetUpperExamples.lean'),('example_traces.json','phase219_example_traces.json')]),
  ('phase219_rank3.py','regenerated_rank3',[('LabelElevenRankThree.lean','phase219_formal/LabelElevenRankThree.lean'),('rank3_trace.json','phase219_rank3_trace.json')])]:
  target=out/subdir
  r=subprocess.run([sys.executable,'-B','-O',BASE/producer,'--out',target],text=True,capture_output=True,timeout=60)
  need(r.returncode==0,'regeneration '+producer+' '+r.stderr)
  for new,old in outputs:need((target/new).read_bytes()==(BASE/old).read_bytes(),'exact regenerated bytes '+old)
  inputs[producer]=sha(BASE/producer)
  regenerations.append(dict(producer=producer,stdout=r.stdout,outputs={old:sha(BASE/old) for new,old in outputs}))
 def run(label,source,expected=True):
  text=source.read_text()
  if expected:need(not re.search(r'\b(sorry|admit|native_decide)\b|^\s*axiom\s',text,re.M),'proof hole '+label)
  start=time.monotonic()
  r=subprocess.run([a.lean,'-o',app/(label+'.olean'),source],cwd=sources,env=env,text=True,capture_output=True,timeout=600)
  (out/(label+'.stdout')).write_text(r.stdout);(out/(label+'.stderr')).write_text(r.stderr)
  need((r.returncode==0)==expected,label+' exit '+(r.stdout+r.stderr)[-5000:])
  reports=re.findall(r"'([^']+)' depends on axioms:\s*\[([^\]]*)\]",r.stdout+r.stderr)
  if expected:
   need(not re.search('warning:|error:|sorryAx',r.stdout+r.stderr),'unclean build '+label)
   need(all(set(re.findall(r'[\w.]+',v))<={'propext','Quot.sound','Classical.choice'} for _,v in reports),'axiom boundary '+label)
  else:need('error:' in r.stdout+r.stderr,'intended rejection '+label)
  runs.append(dict(label=label,exit_code=r.returncode,seconds=time.monotonic()-start,source_sha256=sha(source),declarations=[k for k,v in reports],stdout_sha256=sha(out/(label+'.stdout')),stderr_sha256=sha(out/(label+'.stderr'))))
 for name in ['CosetUpperCertificate','CosetUpperExamples','LabelElevenRankThree']:
  src=BASE/'phase219_formal'/(name+'.lean');dst=sources/src.name;shutil.copyfile(src,dst);inputs[str(src.relative_to(BASE))]=sha(src);run(name,dst)
 core=(sources/'CosetUpperCertificate.lean').read_text()
 for label,old,new in [
  ('unchecked_tree','if reps v = reps u ++ [s] then','if True then'),
  ('unchecked_relator','if p.map Edge.letter ++ [s] ++ (q.map Edge.letter).reverse ∈ rels then','if True then')]:
  need(core.count(old)==1,'unique mutation site '+label)
  path=sources/(label+'.lean');path.write_text(core.replace(old,new,1));run(label,path,False)
 expected_counts={'CosetUpperCertificate':13,'CosetUpperExamples':9,'LabelElevenRankThree':3}
 for r in runs:
  if r['label'] in expected_counts:need(len(r['declarations'])==expected_counts[r['label']],'declaration census '+r['label'])
 need(inputs=={p:sha(BASE/p) for p in inputs},'input stability')
 report=dict(status='P219_FORMAL_REPLAY_PASS',inputs=inputs,regenerations=regenerations,lean=version,lean_sha256=sha(a.lean.resolve()),dependency_revisions=checked,newly_built_mathlib_modules=built,cached_objects_trusted=True,cached_files_linked=links,runs=runs,
  formal_scope='General executable checker soundness and actual presented-group index theorem; kernel-checked rank-two traces and direct proof-carrying replay of all rank-three transitions.',
  rank3_index_upper_bound=1024,rank4_and_rank5_formalized=False,full_F014_refutation_formalized=False,native_decide_used=False)
 (out/'report.json').write_text(json.dumps(report,indent=2)+'\n');print('P219_FORMAL_REPLAY_PASS')
if __name__=='__main__':main()
