#!/usr/bin/env python3
"""Independent vector-composition check of a literal infinite monomial image.

Also computes the translation rank of this image via finite Schreier generators.
It does not assert that the original presented group equals its image.
"""
import argparse
from collections import deque
from fractions import Fraction
from hashlib import sha256
import json
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--data', type=Path, default=Path(__file__).with_name('phase32_L003_voltage.json'))
    parser.add_argument('--output', required=True, type=Path)
    args = parser.parse_args()
    if args.output.exists():
        raise SystemExit('Refusing to overwrite an existing report')
    source = args.data.read_bytes()
    data = json.loads(source)
    n = data['degree']
    assert n == 216
    one = (tuple(range(n)), (0,) * n)
    generators = [(tuple(j-1 for j in p), tuple(w))
                  for p, w in zip(data['permutations'], data['weights'])]
    assert len(generators) == 3
    for p, w in generators:
        assert sorted(p) == list(range(n)) and len(w) == n
        assert all(type(a) is int and a in {-1, 0, 1} for a in w)

    def product(a, b):
        p, v = a
        q, w = b
        return tuple(q[i] for i in p), tuple(v[k]+w[p[k]] for k in range(n))

    def inverse(a):
        p, v = a
        q = [0] * n
        for i, j in enumerate(p):
            q[j] = i
        return tuple(q), tuple(-v[q[k]] for k in range(n))

    def power(a, k):
        if k < 0:
            return power(inverse(a), -k)
        out = one
        while k:
            if k % 2:
                out = product(out, a)
            a = product(a, a)
            k //= 2
        return out

    def prod(*items):
        out = one
        for a in items:
            out = product(out, a)
        return out

    x, y, z = generators
    for a in generators:
        assert product(a, inverse(a)) == product(inverse(a), a) == one
    parameter = prod(y, power(prod(z, y), 2))
    relators = [power(x, 6), power(y, 3), power(z, 2),
                power(prod(z, x), 3), power(prod(z, y), 6),
                power(prod(inverse(x), y), 2),
                power(prod(inverse(y), power(x, -2)), 3),
                power(prod(z, power(x, 3)), 2),
                prod(inverse(x), z, power(prod(inverse(y), z), 2),
                     z, x, power(prod(z, y), 2)), power(parameter, 6)]
    assert len(relators) == 10 and all(r == one for r in relators)
    assert all(power(parameter, k) != one for k in (1, 2, 3))
    witness = power(prod(x, y, x, z), 2)
    assert witness[0] == one[0] and witness[1][0] == -1

    # Enumerate the finite permutation image, retaining a lifted transversal.
    lifts = {one[0]: one}
    pending = deque([one[0]])
    while pending:
        p = pending.popleft()
        for a in generators:
            candidate = product(lifts[p], a)
            if candidate[0] not in lifts:
                lifts[candidate[0]] = candidate
                pending.append(candidate[0])
        assert len(lifts) <= 216
    assert len(lifts) == 216
    translations = []
    for p, lift in lifts.items():
        for a in generators:
            candidate = product(lift, a)
            loop = product(candidate, inverse(lifts[candidate[0]]))
            assert loop[0] == one[0]
            translations.append(loop[1])
    assert len(translations) == 648

    # Exact rational row reduction: rank of the lattice generated by the
    # complete Schreier list, not a rank estimate from one selected translation.
    basis = []
    pivots = []
    independent_originals = []
    for row in translations:
        reduced = list(map(Fraction, row))
        for pivot, old in zip(pivots, basis):
            coefficient = reduced[pivot]
            reduced = [a-coefficient*b for a,b in zip(reduced,old)]
        pivot = next((i for i,v in enumerate(reduced) if v), None)
        if pivot is not None:
            coefficient = reduced[pivot]
            basis.append([v/coefficient for v in reduced])
            pivots.append(pivot)
            independent_originals.append(row)
    assert len(basis) == 6
    # Every reduced basis vector has its own pivot and zero at earlier pivots.
    assert all(row[pivots[i]] == 1 and all(row[p] == 0 for p in pivots[:i])
               for i,row in enumerate(basis))
    for row in translations + [witness[1]]:
        reduced = list(map(Fraction, row))
        for pivot, old in zip(pivots, basis):
            coefficient = reduced[pivot]
            reduced = [a-coefficient*b for a,b in zip(reduced,old)]
        assert not any(reduced)
    report = {
        'status': 'PASS', 'data_sha256': sha256(source).hexdigest(),
        'checker_sha256': sha256(Path(__file__).read_bytes()).hexdigest(),
        'independence': 'Vector composition and binary exponentiation; no imports from author checker, GAP or SymPy.',
        'states': n, 'relators': 10, 'relator_state_equalities': 2160,
        'parameter_word_order': 6, 'witness': '(x y x z)^2',
        'witness_permutation_identity': True,
        'witness_translation': witness[1], 'first_translation': -1,
        'finite_permutation_image_order': 216,
        'complete_schreier_translations': 648,
        'translation_lattice_rank': 6,
        'independent_integer_vectors': independent_originals,
        'rational_elimination_pivots': pivots,
        'scope': 'Exact monomial image is infinite and has a free abelian translation kernel of rank6 and permutation quotient of order216, via the written Schreier argument. The source group may be larger. No geometric realization, parameter-exact finite quotient, or open-problem resolution is asserted.'
    }
    args.output.write_text(json.dumps(report,indent=2)+'\n')
    print('ROOT_L003_PASS: 2160 relator states; infinite translation; image quotient216 and translation rank6')


if __name__ == '__main__':
    main()
