"""Verify supplied finite sets, pair partition, coset graphs and design witnesses."""
import sys
if sys.flags.optimize:raise RuntimeError('Ordinary Python required')
sys.dont_write_bytecode=True
from collections import Counter
from itertools import combinations
from math import comb

def need(b,m):
    if not b:raise ValueError(m)

def mul(a,b):return tuple(b[x] for x in a)

def inverse(a):
    b=[0]*len(a)
    for i,x in enumerate(a):b[x]=i
    return tuple(b)

def distance(adjacency,root):
    d=[-1]*len(adjacency);d[root]=0;queue=[root]
    for u in queue:
        for v in adjacency[u]:
            if d[v]<0:d[v]=d[u]+1;queue.append(v)
    need(len(queue)==len(adjacency),'connected graph')
    return d

def root_cycle(adjacency,root):
    # Shortest path between distinct neighbors in the graph with root removed.
    color=[-1]*len(adjacency);dist=[-1]*len(adjacency);queue=list(adjacency[root])
    for x in queue:color[x]=x;dist[x]=0
    best=len(adjacency)+1
    for u in queue:
        for v in adjacency[u]:
            if v==root:continue
            if color[v]<0:
                color[v]=color[u];dist[v]=dist[u]+1;queue.append(v)
            elif color[v]!=color[u]:best=min(best,dist[u]+dist[v]+3)
    need(best<=len(adjacency),'cycle through chosen root')
    return best

def verify(data,result):
    elements=[tuple(p) for p in data['group_model']['elements']]
    generators=[tuple(p) for p in data['group_model']['generators']]
    identity=tuple(range(11));idx={p:i for i,p in enumerate(elements)}
    need(len(elements)==len(idx)==7920 and elements[0]==identity,'acquired group array')
    right=[[idx[mul(p,g)] for p in elements] for g in generators]
    reached={0};queue=[0]
    for u in queue:
        for action in right:
            v=action[u]
            if v not in reached:reached.add(v);queue.append(v)
    need(len(reached)==7920,'model generated by named pair')
    subs=[frozenset(row) for row in result['subgroup_elements']]
    need(len(subs)==39,'39 acquired subgroups')
    for row,gens in zip(subs,data['subgroup_generators']):
        gs=[tuple(g) for g in gens];seen={0};queue=[0]
        need(0 in row and all(0<=x<7920 for x in row),'subgroup domain')
        for u in queue:
            for g in gs:
                v=idx[mul(elements[u],g)];need(v in row,'subgroup generator closure')
                if v not in seen:seen.add(v);queue.append(v)
        need(seen==row,'subgroup generated exactly')
    maxes=result['maximal_subgroups'];sets=[frozenset(r['elements']) for r in maxes]
    need(len(sets)==len(set(sets))==result['number_of_maximal_subgroups'],'distinct maximal sets')
    maximum=data['maximal_class_positions'];types=[r['class_position'] for r in maxes]
    for r,h in zip(maxes,sets):
        need(r['class_position'] in maximum,'maximal class position')
        g=elements[r['conjugator']];ig=inverse(g)
        need(h=={idx[mul(mul(ig,elements[x]),g)] for x in subs[r['class_position']-1]},'literal maximal conjugator')
    actions=result['maximal_action']
    need(len(actions)==len(generators),'one maximal action per generator')
    for p,g in zip(actions,generators):
        need(sorted(p)==list(range(len(sets))),'permutation of maximal domain');ig=inverse(g)
        for i,h in enumerate(sets):need(sets[p[i]]=={idx[mul(mul(ig,elements[x]),g)] for x in h},'exact conjugation action')
    for k in maximum:
        starts=[i for i,t in enumerate(types) if t==k and sets[i]==subs[k-1]]
        need(len(starts)==1,'maximal representative included');seen={starts[0]};queue=starts[:]
        for u in queue:
            for p in actions:
                v=p[u];need(types[v]==k,'class action remains in class')
                if v not in seen:seen.add(v);queue.append(v)
        need(seen=={i for i,t in enumerate(types) if t==k},'complete single class orbit')
    pairs=list(combinations(range(len(sets)),2));positions={p:i for i,p in enumerate(pairs)}
    assignment=result['pair_orbit_assignment'];orbits=result['pair_orbits']
    need(len(pairs)==result['unordered_pairs']==len(assignment),'entire unordered-pair domain')
    need(len(orbits)==result['number_of_orbits']==len(result['graphs']),'one graph per pair orbit')
    covered=set()
    for number,r in enumerate(orbits):
        rows=r['pair_positions'];need(rows and len(rows)==len(set(rows)) and not covered.intersection(rows),'disjoint nonempty pair classes')
        need(all(0<=x<len(pairs) and assignment[x]==number for x in rows),'pair assignment agrees')
        need(list(pairs[rows[0]])==r['representative'],'actual representative')
        covered.update(rows);allowed=set(rows);seen={rows[0]};queue=[rows[0]]
        for j in queue:
            u,v=pairs[j]
            for a in actions:
                k=positions[tuple(sorted([a[u],a[v]]))];need(k in allowed,'pair class closed')
                if k not in seen:seen.add(k);queue.append(k)
        need(seen==allowed,'pair class connected under generators')
    need(covered==set(range(len(pairs))),'all unordered pairs covered')
    cosets_checked=0;design_subsets=0
    for number,g in enumerate(result['graphs']):
        need(g['orbit']==number and g['pair']==orbits[number]['representative'],'graph tied to pair')
        h,k=g['pair'];intersection=sets[h]&sets[k]
        need(g['subgroup_classes']==[types[h],types[k]] and g['subgroup_orders']==[len(sets[h]),len(sets[k])],'actual parabolics')
        need(g['intersection_elements']==sorted(intersection) and g['intersection_order']==len(intersection),'actual intersection')
        c,w=g['intersection_class_witness'];x=elements[w];ix=inverse(x)
        need(intersection=={idx[mul(mul(ix,elements[u]),x)] for u in subs[c-1]},'literal intersection conjugator')
        assignments=g['coset_assignment'];representatives=g['coset_representatives'];sizes=g['type_sizes']
        for subgroup,part,reps,n in zip([sets[h],sets[k]],assignments,representatives,sizes):
            need(len(part)==7920 and len(reps)==n and set(part)==set(range(n)),'coset assignment domain')
            actual=[set() for _ in range(n)]
            for u,v in enumerate(part):actual[v].add(u)
            for j,r in enumerate(reps):
                expected={idx[mul(elements[u],elements[r])] for u in subgroup}
                need(actual[j]==expected,'complete exact right coset');cosets_checked+=1
        adjacency=[set() for _ in range(sum(sizes))]
        for u,v in zip(*assignments):adjacency[u].add(sizes[0]+v);adjacency[sizes[0]+v].add(u)
        need(g['adjacency']==[sorted(row) for row in adjacency],'literal nonempty-intersection adjacency')
        need(all(len(row)>=2 for row in adjacency),'firmness')
        metric=g['metrics'];d1=max(distance(adjacency,0));d2=max(distance(adjacency,sizes[0]))
        girths=[root_cycle(adjacency,r) for r in [0,sizes[0]]]
        need(girths[0]==girths[1] and girths[0]%2==0,'both transitive types give same even girth')
        need(metric['point_diameter']==d1 and metric['line_diameter']==d2 and metric['girth']==girths[0] and metric['gonality']*2==girths[0],'independent rooted metric checks')
        need(metric['eccentricities']==[d1]*sizes[0]+[d2]*sizes[1],'all type eccentricities via transitivity')
        edges=sum(map(len,adjacency))//2
        need(metric['graph_vertices']==sum(sizes) and metric['graph_edges']==edges and edges*len(intersection)==7920,'edge count and chamber stabilizer')
        for side,d in enumerate(g['designs']):
            pp=list(range(sizes[0])) if side==0 else list(range(sizes[0],sum(sizes)))
            bb=list(range(sizes[0],sum(sizes))) if side==0 else list(range(sizes[0]))
            pindex={x:i for i,x in enumerate(pp)}
            blocks=[tuple(sorted(pindex[x] for x in adjacency[b])) for b in bb]
            need(d['blocks']==[list(row) for row in blocks] and d['v']==len(pp) and d['b']==len(bb),'actual design orientation')
            need(len({len(row) for row in blocks})==1 and d['k']==len(blocks[0]) and d['distinct_blocks']==len(set(blocks)),'design block sizes and repetitions')
            if d['complete_incidence']:
                need(d['k']==d['v'] and d['uniform_all_t_through']==d['k'] and d['constant_lambda']==len(bb),'complete-incidence formula')
                continue
            need(d['k']<d['v'],'proper block size')
            levels=d['uniform_counts'];need([r['t'] for r in levels]==list(range(1,len(levels)+1)),'consecutive design strengths')
            for level in levels:
                t=level['t'];counts=Counter(s for b in blocks for s in combinations(b,t))
                need(len(counts)==comb(len(pp),t) and set(counts.values())=={level['lambda_value']} and level['subsets_checked']==len(counts),'all-subsets design certificate')
                design_subsets+=len(counts)
            fail=d['first_failure']
            if fail is not None:
                t=fail['t'];need(t==len(levels)+1,'first failed strength')
                need(all(len(s)==t and len(set(s))==t and all(0<=x<len(pp) for x in s) for s in fail['subsets']),'failure subset domain')
                counts=[sum(set(s)<=set(b) for b in blocks) for s in fail['subsets']]
                need(counts==fail['counts'] and counts[0]!=counts[1],'explicit unequal design counts')
            else:need(len(levels)==d['k'] or not d['all_subset_checks_complete'],'maximal or explicitly partial design strength')
    return dict(status='PASS_L036_LITERAL_M11_GRAPH_CERTIFICATE',group_order=7920,maximal_subgroups=len(sets),unordered_pairs=len(pairs),pair_orbits=len(orbits),cosets_checked=cosets_checked,uniform_design_subsets_checked=design_subsets,independent_girth_method='multi-source search after root deletion, both transitive types',new_subgroup_classification=False,whole_source_accepted=False)
