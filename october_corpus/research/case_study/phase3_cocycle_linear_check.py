"""Solve the marked cyclic-extension equations by exact modular linear algebra.

The seed is Q=D8 x C2, marked a=(r,b), b=b, c=c. The kernel is
A=Z/2^k, canonically generated by (bc)^2. No group is enumerated upstairs.
NumPy int64 is exact in the checked range; the modulus bound prevents overflow.
"""
from hashlib import sha256
import json
from pathlib import Path

import numpy as np


ELEMENTS = [(i, j, z) for i in range(4) for j in range(2) for z in range(2)]
INDEX = {g: i for i, g in enumerate(ELEMENTS)}
IDENTITY = INDEX[(0, 0, 0)]
MARKS = [INDEX[g] for g in [(1, 1, 0), (0, 1, 0), (0, 0, 1)]]


def multiply(g, h):
    i, j, z = ELEMENTS[g]
    l, m, w = ELEMENTS[h]
    return INDEX[((i + (-1) ** j * l) % 4, j ^ m, z ^ w)]


PRODUCT = [[multiply(g, h) for h in range(16)] for g in range(16)]
PAIRS = {(g, h): i for i, (g, h) in enumerate(
    (g, h) for g in range(1, 16) for h in range(1, 16))}
VARIABLES = len(PAIRS) + 3


def equations(k, u):
    modulus = 2 ** k
    action = [pow(-u, i, modulus) * (-1) ** (j + z) % modulus
              for i, j, z in ELEMENTS]
    assert all(action[PRODUCT[g][h]] == action[g] * action[h] % modulus
               for g in range(16) for h in range(16))
    assert [action[g] for g in MARKS] == [u, modulus - 1, modulus - 1]
    rows, rhs = [], []

    def add_f(row, g, h, coefficient):
        if g and h:
            row[PAIRS[g, h]] += coefficient

    for g in range(1, 16):
        for h in range(1, 16):
            for z in range(1, 16):
                row = np.zeros(VARIABLES, dtype=np.int64)
                add_f(row, g, h, 1)
                add_f(row, PRODUCT[g][h], z, 1)
                add_f(row, h, z, -action[g])
                add_f(row, g, PRODUCT[h][z], -1)
                rows.append(row)
                rhs.append(0)

    # Words use labels 0=a, 1=b, 2=c. The last word is the chosen kernel generator.
    relations = [([0, 0], 0), ([1, 1], 0), ([2, 2], 0),
                 ([0, 2, 0, 2], 0), ([0, 1] * 4, 0), ([1, 2] * 2, 1)]
    for word, value in relations:
        row = np.zeros(VARIABLES, dtype=np.int64)
        state = IDENTITY
        for label in word:
            g = MARKS[label]
            row[len(PAIRS) + label] += action[state]
            add_f(row, state, g, 1)
            state = PRODUCT[state][g]
        assert state == IDENTITY
        rows.append(row)
        rhs.append(value)
    return np.array(rows) % modulus, np.array(rhs, dtype=np.int64), action


def solution_exponent(matrix, rhs, k):
    """Return log2(number of solutions mod 2^k), or None if inconsistent.

    An odd coefficient is a unit pivot. When all remaining coefficients are
    even, divide the equations and modulus by two; every remaining variable
    contributes one free high bit. This is elimination over a finite DVR.
    """
    assert 1 <= k <= 12
    modulus = 2 ** k
    a = matrix.copy() % modulus
    b = rhs.copy() % modulus
    free_bits = 0
    layers = []
    while modulus > 1:
        rank = 0
        while rank < min(a.shape):
            positions = np.argwhere(a[rank:, rank:] % 2)
            if not len(positions):
                break
            row, col = positions[0] + rank
            a[[rank, row]] = a[[row, rank]]
            b[[rank, row]] = b[[row, rank]]
            a[:, [rank, col]] = a[:, [col, rank]]
            inverse = pow(int(a[rank, rank]), -1, modulus)
            a[rank, rank:] = a[rank, rank:] * inverse % modulus
            b[rank] = b[rank] * inverse % modulus
            if rank + 1 < len(a):
                factors = a[rank + 1:, rank].copy()
                a[rank + 1:, rank:] = (
                    a[rank + 1:, rank:] - factors[:, None] * a[rank, rank:]
                ) % modulus
                b[rank + 1:] = (b[rank + 1:] - factors * b[rank]) % modulus
            rank += 1
        layers.append({"modulus": modulus, "unit_pivots": rank})
        a = a[rank:, rank:]
        b = b[rank:]
        if np.any(b % 2):
            return None, layers
        assert not np.any(a % 2)
        free_bits += a.shape[1]
        a //= 2
        b //= 2
        modulus //= 2
    return free_bits, layers


def verify_elimination():
    # Independent brute-force checks of the counting algorithm on small systems.
    from itertools import product
    rng = np.random.default_rng(20261009)
    checked = 0
    for k in [1, 2, 3]:
        modulus = 2 ** k
        for rows, cols in [(1, 1), (2, 2), (2, 3), (4, 2)]:
            for _ in range(12):
                a = rng.integers(0, modulus, (rows, cols), dtype=np.int64)
                b = rng.integers(0, modulus, rows, dtype=np.int64)
                expected = sum(all((a @ x - b) % modulus == 0)
                               for x in map(np.array, product(range(modulus), repeat=cols)))
                exponent, _ = solution_exponent(a, b, k)
                actual = 0 if exponent is None else 2 ** exponent
                assert actual == expected, (a, b, k, actual, expected)
                checked += 1
    return checked


def main():
    small_checks = verify_elimination()
    results = []
    for k in [3, 4, 6, 8]:
        modulus = 2 ** k
        actions = sorted({1, modulus - 1, 1 + modulus // 2, modulus // 2 - 1})
        for u in actions:
            matrix, rhs, _ = equations(k, u)
            exponent, layers = solution_exponent(matrix, rhs, k)
            gauge_exponent = k * 15
            count = 0 if exponent is None else 2 ** (exponent - gauge_exponent)
            assert exponent is None or exponent >= gauge_exponent
            assert count == (1 if u in [1, 1 + modulus // 2] else 0)
            row = {"kernel_exponent": k, "kernel_order": modulus, "a_action": u,
                   "equations": len(rhs), "unknowns": VARIABLES,
                   "log2_solutions": exponent, "log2_free_section_changes": gauge_exponent,
                   "marked_isomorphism_classes": count, "elimination_layers": layers}
            results.append(row)
            print(f"k={k} u={u}: marked classes={count}", flush=True)
    source = Path(__file__)
    report = {"status": "PASS", "arithmetic": "exact integer arithmetic modulo powers of two",
              "numpy_version": np.__version__, "source_sha256": sha256(source.read_bytes()).hexdigest(),
              "independent_small_solver_checks": small_checks,
              "scope": "Fixed quotient D8 x C2, four kernel orders and all four involutory actions; finite validation of the uniform written linear-extension theorem.",
              "results": results}
    source.with_suffix(".json").write_text(json.dumps(report, indent=2) + "\n")
    print("ALL MARKED COCYCLE LINEAR SYSTEMS PASS")


if __name__ == "__main__":
    main()
