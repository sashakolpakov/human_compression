import argparse,itertools,json,math,time
from pathlib import Path
N=12
ONE=tuple(range(N))
def need(x,m):
 if not x:raise RuntimeError(m)
def perm(*cycles):
 p=list(ONE)
 for cyc in cycles:
  for a,b in zip(cyc,cyc[1:]+cyc[:1]):p[a-1]=b-1
 return tuple(p)
def mul(a,b):return tuple(b[x] for x in a)
def inv(a):
 q=list(ONE)
 for i,x in enumerate(a):q[x]=i
 return tuple(q)
def power(a,n):
 q=ONE
 for _ in range(n):q=mul(q,a)
 return q
def word(*xs):
 q=ONE
 for x in xs:q=mul(q,x)
 return q
def conj(a,b):return word(inv(b),a,b)
def subgroup(gens):
 seen={ONE};todo=[ONE]
 for a in todo:
  for g in gens:
   b=mul(a,g)
   if b not in seen:seen.add(b);todo.append(b)
   need(len(seen)<=100000,'Only proper small subgroups may be enumerated')
 return seen
def parity(g):return sum(g[i]>g[j] for i in range(N) for j in range(i+1,N))%2
def symmetric(points):
 pts=[p-1 for p in points]
 for images in itertools.permutations(pts):
  q=list(ONE)
  for i,v in zip(pts,images):q[i]=v
  yield tuple(q)
def orbits(gens,points=range(1,12)):
 remaining=set(points);out=[]
 while remaining:
  a=min(remaining);seen={a};todo=[a]
  for v in todo:
   for g in gens:
    w=g[v-1]+1
    if w not in seen:seen.add(w);todo.append(w)
  remaining-=seen;out.append(sorted(seen))
 return out
